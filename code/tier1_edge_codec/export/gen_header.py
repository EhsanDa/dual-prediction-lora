"""
gen_header.py  --  Python -> edge_config.h. Blueprint 10.1.

THERE IS ALMOST NOTHING TO EXPORT, AND THAT IS THE POINT
========================================================
The usual TinyML pipeline ships a trained weight matrix. Tier 1 adapts online,
so no weights are shipped at all: this header carries about twenty commissioning
constants, three of which are per meter. The algorithm lives in edge_codec.c.
That is the opposite weighting from a typical export and it is worth stating in
the write-up -- it is why one firmware image runs on every meter in a fleet
whose loads span four orders of magnitude.

Per meter: NODE_ID, SCALE_K (from choose_scale) and EPS_INIT (from
mase_scale * alpha). Everything else is global.
"""

import argparse
import json
import os
import sys

import numpy as np

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if REPO not in sys.path:
    sys.path.insert(0, REPO)

from edge.codec import EPS_INF, CodecParams          # noqa: E402
from sim.run_codec import Store, choose_scales, eps_for_alpha   # noqa: E402

TEMPLATE = """\
/* edge_config.h -- GENERATED by export/gen_header.py. Do not edit.
 *
 * Commissioning constants for ONE meter. The algorithm is in edge_codec.c;
 * this file is only the numbers, because the Tier-1 model adapts online and
 * there are no trained weights to ship.
 *
 * RESOLUTION. Weights are Q20 in int32, not Q12 in int16. At Q12, with loads
 * around 1e4 device units, the NLMS update quantised to 2 LSBs at k_mu = 2 and
 * to ZERO by k_mu = 4: the filter could only be too fast or frozen, and the
 * measured consequence was that it lost to a frozen persistence predictor.
 * Q20 costs 12 B of SRAM and gives the step size a usable range.
 *
 * store        : {store}
 * client       : {client}
 * alpha        : {alpha}
 * generated by : export/gen_header.py
 */
#ifndef EDGE_CONFIG_H
#define EDGE_CONFIG_H

/* ---- global: identical in every firmware image ---- */
#define TAP_LIST        {{ {tap_list} }}
#define N_TAPS          {n_taps}
#define N_W             {n_w}          /* taps + bias */
#define BUF_LEN         {buf_len}
#define W_Q             {w_q}          /* Q20: see the resolution note below */
#define W_INIT          {{ {w_init} }}
#define W_CLAMP         {w_clamp}L
#define BIAS_INPUT      {bias_input}       /* NOT 1<<W_Q -- see edge/codec.py */
#define U_CLAMP         {u_clamp}
#define U_MIN           {u_min}        /* see edge_codec.c: keeps e int16 */
#define K_MU            {k_mu}         /* effective mu = 2^-K_MU */
#define S_SHIFT         {s_shift}      /* EWMA alpha = 1/32 */
#define K_EVENT         {k_event}
#define N_MAX_TX        {n_max_tx}     /* daily exception budget */
#define EVENT_WARMUP    {event_warmup} /* hours before EVENT may fire */
#define SYNC_SAFE       {sync_safe}      /* 1 = update on the reconstruction */
#define ADAPT           {adapt}      /* 0 = send-on-delta baseline */
#define MAX_TAP         {max_tap}
#define N_CARRY         {n_carry}      /* taps the ring cannot reach */
#define N_CARRY_MAX     {n_carry_max}      /* >= 1 so the array is never zero-length */

/* ---- per meter ---- */
#define NODE_ID         {node_id}
#define SCALE_K         {scale_k}      /* q = 2^SCALE_K kWh per device unit */
#define EPS_INIT        {eps_init}     /* device units; {eps_note} */
#define EPS_NEVER       0xFFFFu        /* EPS_INIT == this means alpha = inf */

/* ---- provenance, so a flashed node can be traced back ---- */
#define FEATURE_SPEC_HASH "{fsh}"
#define MASE_SCALE_KWH_X1000 {mase_x1000}L

#endif /* EDGE_CONFIG_H */
"""


def render(params: CodecParams, node_id, scale_k, eps_init, alpha, store_dir,
           fsh, mase_scale):
    taps = list(params.taps) + [0] * 8
    eps_note = ("alpha = inf: exceptions disabled, daily resync only"
                if eps_init is EPS_INF else
                f"alpha * mase_scale / 2^k, alpha = {alpha:g}")
    return TEMPLATE.format(
        store=store_dir, client=node_id, alpha=("inf" if eps_init is EPS_INF
                                                else f"{alpha:g}"),
        tap_list=", ".join(str(t) for t in params.taps),
        n_taps=len(params.taps), n_w=params.n_w, buf_len=params.buf_len,
        w_q=params.w_q, w_init=", ".join(str(x) for x in params.w_init),
        w_clamp=params.w_clamp, u_clamp=params.u_clamp, u_min=params.u_min,
        k_mu=params.k_mu, s_shift=params.s_shift, k_event=params.k_event,
        n_max_tx=params.n_max_tx, event_warmup=params.event_warmup,
        bias_input=params.bias_input, sync_safe=int(params.sync_safe),
        adapt=int(params.adapt), max_tap=params.max_tap,
        n_carry=params.n_carry, n_carry_max=max(params.n_carry, 1),
        node_id=node_id, scale_k=scale_k,
        eps_init=("EPS_NEVER" if eps_init is EPS_INF else f"{eps_init}u"),
        eps_note=eps_note, fsh=fsh[:32],
        mase_x1000=int(round(mase_scale * 1000)) if np.isfinite(mase_scale) else 0)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data_dir", default="synth_data")
    ap.add_argument("--client", type=int, default=0)
    ap.add_argument("--alpha", default="1.0")
    ap.add_argument("--pretrained", default=None,
                    help="edge_pretrained.json from sim/pretrain.py. Without "
                         "it the node ships the persistence initialisation, "
                         "which is ablation row A, not the proposed model.")
    ap.add_argument("--out", default="firmware/edge_config.h")
    a = ap.parse_args()
    alpha = float("inf") if a.alpha == "inf" else float(a.alpha)

    store = Store.load(a.data_dir)
    params = CodecParams()
    if a.pretrained:
        import json as _json
        params = params.with_w_init(_json.load(open(a.pretrained))["w_global_q"])
    k, _ = choose_scales(store)
    eps, degenerate = eps_for_alpha(store, k, alpha)
    c = a.client
    assert 0 <= c < store.M, f"client {c} not in this store (M={store.M})"
    txt = render(params, c, int(k[c]), eps[c], alpha, a.data_dir,
                 store.manifest["feature_spec_hash"], store.mase_scale[c])
    os.makedirs(os.path.dirname(a.out) or ".", exist_ok=True)
    with open(a.out, "w") as f:
        f.write(txt)
    q = 2.0 ** int(k[c])
    print(f"wrote {a.out}")
    print(f"  w_init = {'GLOBAL RIDGE (section 3.2)' if a.pretrained else 'persistence -- row A, not the proposed model'}")
    print(f"  client {c}: k={int(k[c])} (q={q:g} kWh/unit)  "
          f"eps={eps[c]}  mase_scale={store.mase_scale[c]:.3f} kWh"
          + ("  [DEGENERATE mase_scale, eps fell back]" if degenerate[c] else ""))


if __name__ == "__main__":
    main()
