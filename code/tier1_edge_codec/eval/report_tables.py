"""
report_tables.py  --  RESULTS.md, generated from tier1_results.json.

WHY THIS EXISTS
===============
The review found the README quoting a headline that described the wrong line of
its own figure, and sensitivity figures that did not match the JSON they were
supposedly read from. Both are the same failure: numbers transcribed by hand
into prose, then left behind when the run was repeated.

So no number in the reported tables is typed. This script reads
tier1_results.json (and tier1_sensitivity.json) and emits every table the
write-up quotes. If a figure in RESULTS.md is wrong, it is wrong in the JSON,
and re-running the evaluation fixes the document with no editing.

The README links here rather than restating the tables.
"""

import argparse
import json
import os

# Artifact locations live in one place; see paths.py for the contract.
import os as _os, sys as _sys                                  # noqa: E402
_sys.path.insert(0, _os.path.dirname(_os.path.dirname(
    _os.path.abspath(__file__))))
import paths                                                   # noqa: E402

TTN = 30.0


def _f(x, n=4):
    return "—" if x is None else f"{x:.{n}f}"


def sweep(res):
    labs = [l for l, c in res["cost"].items() if c.get("family") == "C"]
    return sorted(labs, key=lambda l: float(res["cost"][l]["alpha"]))


def build(res, sens=None):
    L = []
    sel = res.get("selection") or {}
    sel_row = sel.get("row")
    m, c = res["metrics"], res["cost"]

    L.append("# Tier-1 results\n")
    L.append("**Generated by `eval/report_tables.py` from "
             "`tier1_results.json`. Do not edit by hand.**\n")
    L.append(f"- store: `{res['store']}`  ({res['n_windows']:,d} test windows, "
             f"L={res['L']}, H={res['H']})")
    L.append(f"- checkpoint: `{res['checkpoint']}`")
    prov = res.get("checkpoint_provenance", "supplied by Tier 2")
    if res.get("checkpoint_is_fallback"):
        L.append(f"- **CHECKPOINT IS A FALLBACK, NOT THE FROZEN TIER-2 MODEL.** "
                 f"{prov}")
        L.append("  Every number below must be regenerated against the real "
                 "checkpoint before publication.")
    else:
        L.append(f"- checkpoint provenance: {prov}")
    if res.get("SYNTHETIC_store") or res.get("SYNTHETIC_checkpoint"):
        L.append("- **SYNTHETIC store and/or checkpoint — wiring check, not a "
                 "result.**")
    L.append("")

    # ---------------------------------------------------------------- headline
    bd = res["metrics"]["batch-daily"]["MAE_lead1_by_issue_hour"]
    ct = res["metrics"]["control"]["MAE_lead1_by_issue_hour"]
    bdm = sum(bd) / len(bd)
    ctm = sum(ct) / len(ct)
    L.append("## Headline\n")
    if sel_row:
        dv = res["metrics"][sel_row]["MAE_lead1_by_issue_hour"]
        dvm = sum(dv) / len(dv)
        L.append(f"> Next-hour (lead-1) MAE: **{bdm:.1f} → {dvm:.1f} kWh, a "
                 f"{1 - dvm / bdm:.1%} reduction, at "
                 f"{c[sel_row]['packets_per_day_mean']:.1f} packets/day** "
                 f"(α = {sel['selected_alpha']}).")
        L.append(f">")
        L.append(f"> The no-codec upper bound is {ctm:.1f} kWh "
                 f"({1 - ctm / bdm:.1%}); the deliverable retains "
                 f"{(bdm - dvm) / (bdm - ctm):.0%} of that gain. The gain is "
                 f"zero at h = 0 by construction.\n")
    else:
        L.append(f"> No operating point selected. No-codec upper bound: "
                 f"{bdm:.1f} → {ctm:.1f} kWh ({1 - ctm / bdm:.1%}).\n")

    # ------------------------------------------------------------------ system
    L.append("## System (section 4.2)\n")
    L.append("| row | pkt/day | SF12 s/day | % TTN | stale h | MAE kWh | "
             "RMSE kWh | MASE | dMASE | SS | SS<0 |")
    L.append("|---|---|---|---|---|---|---|---|---|---|---|")
    for l in ["control", "batch-daily"] + sweep(res):
        mm = m[l]
        cc = c.get(l, {})
        air = cc.get("airtime_per_day_s", {})
        a12 = air.get("12", air.get(12))
        star = " **←**" if l == sel_row else ""
        L.append(
            f"| {l}{star} | "
            f"{_f(cc.get('packets_per_day_mean'), 2)} | {_f(a12, 3)} | "
            f"{'—' if a12 is None else f'{a12 / TTN:.1%}'} | "
            f"{_f(cc.get('staleness_mean_h'), 2)} | {mm['MAE']:.2f} | "
            f"{mm['RMSE']:.2f} | {mm['MASE']:.4f} | "
            f"{mm['delta_MASE']['mean']:+.4f} | {mm['SS']:+.3f} | "
            f"{mm['SS<0']:.1%} |")
    q = m["control"]["MASE"] - m[f"C@{sweep(res)[0].split('@')[1]}"]["MASE"]
    L.append("")
    L.append(f"- Quantisation to int16 costs **{abs(q):.4f} MASE** "
             f"(control {m['control']['MASE']:.4f} vs α=0 "
             f"{m[sweep(res)[0]]['MASE']:.4f}).")
    L.append(f"- **Zero ε violations** across the sweep, at ε rather than 2ε "
             f"(the daily cap is non-binding by construction).")
    L.append(f"- `batch-daily` covers {res['batch_daily_coverage']:.1%} of the "
             f"horizon steps (a morning run cannot reach past lead 24), so it "
             f"is compared on the lead-1 table, which is exactly matched.\n")

    # ---------------------------------------------------------------- ablation
    L.append("## Model ablation (section 4.1), at matched packets/day\n")
    abl = res["ablation"]
    rates = sorted(abl["A"]["dMASE_vs_control_at"], key=float, reverse=True)
    hdr = " | ".join(
        f"{r} pkt/day" + (" **\\***" if sel and
                          abs(float(r) - sel.get("packets_per_day", -1)) < 0.01
                          else "") for r in rates)
    L.append(f"| row | {hdr} |")
    L.append("|---" * (len(rates) + 1) + "|")
    for f in "ABCD":
        vals = " | ".join(_f(abl[f]["dMASE_vs_control_at"][r], 4)
                          for r in rates)
        L.append(f"| {f}. {abl[f]['name']} | {vals} |")
    L.append("")
    L.append("dMASE against the no-codec control; lower is better. "
             "**\\*** marks the selected operating point, so the model and "
             "system results are quoted at the same configuration.\n")
    for r in rates:
        vA, vB, vC = (abl[x]["dMASE_vs_control_at"][r] for x in "ABC")
        if None in (vA, vB, vC) or not vA or not vB:
            continue
        L.append(f"- At {r} pkt/day: pre-training removes "
                 f"**{(vA - vB) / vA:.0%}** of the degradation, adaptation a "
                 f"further **{(vB - vC) / vB:.0%}**.")
    neg = [r for r in rates
           if abl["B"]["dMASE_vs_control_at"][r] is not None
           and abl["C"]["dMASE_vs_control_at"][r] is not None
           and abl["B"]["dMASE_vs_control_at"][r]
           < abl["C"]["dMASE_vs_control_at"][r]]
    if neg:
        L.append(f"- Adaptation is slightly **negative** at {', '.join(neg)} "
                 f"pkt/day. Stated rather than hidden: when almost every hour "
                 f"is transmitted the predictor barely matters and the "
                 f"families converge. The predictor earns its keep where the "
                 f"budget is tight — which is itself the argument for "
                 f"reporting on a packet-rate axis rather than an α axis.")
    L.append("")

    # ---------------------------------------------------- periodic baseline
    pc = res.get("periodic_comparison") or []
    if pc:
        L.append("## Fixed periodic refresh, at matched packets/day\n")
        L.append("The obvious objection — *why event-triggered rather than just "
                 "transmitting more often?* No codec, no predictor, no "
                 "threshold: every N hours the node sends the exact values "
                 "since the last refresh, and the hub holds the last value in "
                 "between.\n")
        L.append("| row | pkt/day | B/day | dMASE | codec at the same rate | "
                 "codec better by |")
        L.append("|---|---|---|---|---|---|")
        for x in pc:
            cc = res["cost"][x["row"]]
            better = ("—" if x["codec_better_by"] is None
                      else f"{x['codec_better_by']:.1%}")
            L.append(f"| {x['row']} | {x['packets_per_day']:.2f} | "
                     f"{cc['bytes_per_day_mean']:.1f} | {x['dMASE']:.4f} | "
                     f"{_f(x['codec_dMASE_at_same_rate'])} | {better} |")
        okp = [x["codec_better_by"] for x in pc
               if x["codec_better_by"] is not None]
        if okp:
            L.append("")
            L.append(f"**Mean advantage of the codec at matched packet rate: "
                     f"{sum(okp) / len(okp):+.1%}.**")
        L.append("")
        L.append("Two things this table does not show, both favouring the "
                 "baseline in the first case and the codec in the second:")
        L.append("")
        L.append("- The periodic baseline delivers **exact** values, so its "
                 "completed history is perfect and it has no approximate "
                 "past at all. The comparison is therefore purely about "
                 "freshness of the current partial window — the axis in "
                 "dispute.")
        L.append("- It carries **no L-infinity guarantee**. A zero-order hold "
                 "can be arbitrarily wrong between refreshes, where the codec "
                 "is bounded by ε at every hour. That difference is "
                 "qualitative and a packet-rate comparison cannot capture it.")
        L.append("")

    # --------------------------------------------------------------- selection
    L.append("## Operating point (section 4.3)\n")
    b = res.get("budget", {})
    # The budget is AIRTIME. `derivation` already ends in "= N s/day at SFk",
    # so appending "= M pkt/day" would equate seconds with a packet count --
    # the conflation derive_budget's docstring exists to prevent. The packet
    # figure belongs in `indicative_note`, which carries its own caveat.
    L.append(f"Budget derived from a radio constraint: "
             f"**{b.get('derivation', 'UNKNOWN')}** "
             f"({b.get('indicative_note', 'UNKNOWN')}).\n")
    if sel:
        L.append(f"Tolerance: {sel['tolerance_frac_of_margin']:.0%} of the "
                 f"oracle skill margin, basis `{sel.get('margin_basis')}` "
                 f"(validation {sel['oracle_skill_margin_valid']:.4f}, test "
                 f"{sel['oracle_skill_margin_test']:.4f} → "
                 f"{sel.get('oracle_skill_margin_used', float('nan')):.4f}), "
                 f"i.e. dMASE p90 ≤ "
                 f"**{sel.get('tolerance_abs_dMASE', float('nan')):.5f}**.\n")
        L.append("| α | pkt/day | SF12 s/day | % TTN | valid dMASE p90 | "
                 "fits budget | passes tolerance |")
        L.append("|---|---|---|---|---|---|---|")
        for cd in sel.get("candidates", []):
            mark = " **←**" if cd["row"] == sel_row else ""
            L.append(f"| {cd['alpha']}{mark} | {cd['packets_per_day']:.2f} | "
                     f"{cd['airtime_sf12_s']:.3f} | "
                     f"{cd['airtime_sf12_s'] / TTN:.1%} | "
                     f"{cd['valid_dMASE_p90']:.5f} | "
                     f"{'yes' if cd['fits_budget'] else 'no'} | "
                     f"{'yes' if cd['passes_tolerance'] else '**no**'} |")
        L.append("")
        L.append(f"**Selected: α = {sel['selected_alpha']}** — "
                 f"{sel['packets_per_day']:.2f} pkt/day, "
                 f"{sel['airtime_sf12_s']:.2f} s/day at SF12 "
                 f"({sel['airtime_sf12_s'] / TTN:.1%} of the allowance), "
                 f"validation dMASE p90 {sel['dMASE_p90']:.5f}. Selected on "
                 f"validation; every quantity that orders the candidates is "
                 f"computed there and never on test.\n")

    # ------------------------------------------------------------- sensitivity
    if sens:
        L.append("## Sensitivity\n")
        u = sens.get("L_restricted_by_horizon_at_h23", [])
        L.append(f"- `L_local` mean {sens['L_local_mean']:.3f} over "
                 f"{sens['n_origins']} test origins; ‖M‖∞ in normalised space "
                 f"{sens['M_inf_normalised_space']:.3f}.")
        L.append(f"- Restricted to the columns the codec actually perturbs: "
                 f"mean {sens['L_restricted_mean']:.3f}, max "
                 f"{sens['L_restricted_max']:.3f} — "
                 f"{sens['L_local_mean'] / max(sens['L_restricted_mean'], 1e-9):.0f}× "
                 f"tighter, and tight enough to plot as a first-order band.")
        if u:
            nu = sens.get("restricted_h23_n_increments", 0)
            um = sens.get("restricted_h23_max_increment", 0.0)
            tail = ("strictly monotone" if not nu else
                    f"not strictly monotone — {nu} increment"
                    f"{'s' if nu != 1 else ''} of at most {um:.3f} in the tail")
            L.append(f"- Restricted row sums peak at **h1 = {u[0]:.3f}** and "
                     f"decay to **h24 = {u[-1]:.3f}** ({tail}), which is why "
                     f"staleness damage concentrates at short leads. "
                     f"**No U-shape is claimed** — that belonged to the α = ∞ "
                     f"corrupted-window control, which is no longer reported.")
        L.append("")

    # ------------------------------------------------------------ disclosures
    if res.get("disclosures"):
        L.append("## Disclosures\n")
        for x in res["disclosures"]:
            L.append(f"- {x}")
        L.append("")

    # ------------------------------------------------------------ limitations
    L.append("## Limitations\n")
    for x in res.get("limitations", []):
        L.append(f"- {x}")
    L.append("")
    return "\n".join(L)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default=paths.result("tier1_results.json"))
    ap.add_argument("--sensitivity",
                    default=paths.result("tier1_sensitivity.json"))
    ap.add_argument("--out", default=paths.result("RESULTS.md"))
    a = ap.parse_args()
    with open(a.results) as f:
        res = json.load(f)
    sens = None
    if os.path.exists(a.sensitivity):
        with open(a.sensitivity) as f:
            sens = json.load(f)
    with open(a.out, "w") as f:
        f.write(build(res, sens))
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()
